await page.getByRole("button", { name: "Create Competition" }).click()
await page.waitForURL(/\/fixtures\/competitions\/[0-9a-f-]+\/participants/)
const EDITION = page.url().match(/competitions\/([0-9a-f-]+)\//)[1]

// Everything this run created goes when it ends, however it ends: the club
// fixtures its issued matches projected (and their notifications), the matches,
// the draw and the competition itself.
let cleaned = false
function cleanup() {
  if (cleaned) return
  cleaned = true
  const matches = `select id from competition_matches where edition_id='${EDITION}'`
  const fixtures = `select fixture_id from competition_match_fixtures where match_id in (${matches})`
  sql(`delete from notifications where data->>'edition_id'='${EDITION}' or data->>'competition_match_id' in (select id::text from competition_matches where edition_id='${EDITION}') or data->>'fixture_id' in (select fixture_id::text from competition_match_fixtures where match_id in (${matches}))`)
  sql(`delete from fixture_conversation_participants where fixture_id in (${fixtures})`)
  sql(`delete from fixture_conversation_subscriptions where fixture_id in (${fixtures})`)
  sql(`delete from fixtures where id in (${fixtures})`)
  sql(`delete from competition_matches where edition_id='${EDITION}'`)
  sql(`delete from competition_stages where edition_id='${EDITION}'`)
  sql(`delete from competition_participants where edition_id='${EDITION}'`)
  const comp = sql(`select competition_id from competition_editions where id='${EDITION}'`)
  sql(`delete from competition_editions where id='${EDITION}'`)
  if (comp) sql(`delete from competitions where id='${comp}'`)
}
process.on("exit", () => {
  try {
    cleanup()
  } catch (e) {
    console.error("cleanup failed:", e)
  }
})
record("details: a Club Admin creates a competition from its name and lands on Participants", Boolean(EDITION), page.url().replace(APP, ""))
const [compId, organiser, format, teamCount, season] = sql(`select c.id, coalesce(c.organiser_club_id::text,''), c.format, c.team_count, s.name from competition_editions e join competitions c on c.id=e.competition_id join seasons s on s.id=e.season_id where e.id='${EDITION}'`).split("|")
record("details: the club organises it, in the current canonical season", organiser === sql("select id from clubs where slug='ovalball-uat-rufc'") && Boolean(season), `${season}`)
record("details: format and team count are saved", format === "league_knockout" && teamCount === "4", `${format} ${teamCount}`)

