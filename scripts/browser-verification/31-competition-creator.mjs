// COMPETITION CREATOR -- from a name to an issued draw, and a club's answer.
// (Fixture Operations brief: Competition Creator wizard and workspace; Competition
// Match is the canonical record; Ovalball clubs are asked; external clubs are
// never blocked; team staff are never organisers.)
//
// One real run, real input events, two real clubs:
//
//   Club Admin of Ovalball UAT RUFC creates "UAT Cup", League + Knockout, four
//   teams: their own Under 12 Boys, Preston Grasshoppers (on Ovalball) and two
//   clubs that are not on Ovalball. Participants are searched and saved, a
//   duplicate is refused, two groups are drawn, a home-and-away league is
//   generated by round, an impossible request is refused with its reason, the
//   knockout is drawn from group places, and the draw is issued.
//
//   Preston's own Club Admin then answers in Competition Requests. The public
//   page shows the schedule, tables and bracket. A Team Manager is turned away.

import { execFileSync } from "node:child_process"
import { launch, newContext, signIn, APP, record, summarise } from "./harness.mjs"

const DB = ["exec", "-i", "supabase_db_ovalball-saas-startup", "psql", "-U", "postgres", "-d", "postgres", "-tAc"]
const sql = (q) => execFileSync("docker", [...DB, q], { encoding: "utf8" }).trim()

const TAG = Date.now().toString(36).slice(-5).toUpperCase()
const NAME = `UAT Cup ${TAG}`
// A round-one date with a clear week either side for both Under 12 Boys teams, so an
// earlier run's issued matches cannot make this run's draft a (correct) clash.
const SEASON_START = sql(`
  with teams as (
    select t.id from teams t join clubs c on c.id = t.club_id
    where c.slug in ('ovalball-uat-rufc', 'preston-grasshoppers-uat') and t.display_name = 'Under 12 Boys' and t.active
  ), start as (
    select greatest(current_date + 14, (select starts_on from seasons where rugby_code='union' and not is_regression_fixture and current_date <= ends_on order by starts_on limit 1)) d
  )
  select (select d from start) + (7 * k)
  from generate_series(0, 30) k
  where not exists (
    select 1 from fixtures f
    where (f.owning_team_id in (select id from teams) or f.opponent_team_id in (select id from teams))
      and f.status <> 'Cancelled'
      and f.kickoff_date between (select d from start) + (7 * k) - 3 and (select d from start) + (7 * k) + 10
  )
  order by k limit 1`)
if (!sql("select 1 from clubs where slug='preston-grasshoppers-uat'")) {
  console.error("Missing UAT data: run supabase/seeds/local_uat_fixture_operations.sql")
  process.exit(1)
}

