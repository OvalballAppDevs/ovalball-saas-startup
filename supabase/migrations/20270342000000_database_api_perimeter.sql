-- Database/API perimeter: explicit grants from the checked-in manifest.
--
-- Identity/Auth Slice 1 (Phase 2 design, section Z). The security contract is
-- supabase/security/perimeter-manifest.json; supabase/tests/js/
-- perimeter_manifest.test.mts fails when the database and that file disagree.
--
-- Before this migration every public table and function carried Supabase's
-- default grants: anon and authenticated held INSERT, UPDATE, DELETE,
-- TRUNCATE, TRIGGER, REFERENCES and MAINTAIN on almost every table, and
-- EXECUTE (through PUBLIC) on every function. Row-level security and in-function
-- checks were the only boundary. After it:
--
--   * future objects created by migrations receive no anon/authenticated
--     privilege and no PUBLIC EXECUTE until their migration grants one;
--   * anon reads public product data (club identity, published club news and
--     announcements, public competitions, published Rugby Hub and regulatory
--     content, plan pricing) through column allowlists and one public view,
--     and executes 9 public entry points plus the 4 helpers its row policies
--     call -- nothing else;
--   * authenticated reads through RLS, writes directly only to the tables the
--     application writes directly, and executes only functions with a
--     consumer;
--   * admin_club_overview is no longer readable anonymously, and returns rows
--     only to Site Admins;
--   * competition_matches.notes and sync_error are no longer readable
--     anonymously; the public schedule and results are unchanged;
--   * service_role keeps exactly the EXECUTE it had.
--
-- Nothing here changes a row-level security policy's meaning, and no object is
-- dropped.

-- ---------------------------------------------------------------------
-- 1. Default privileges for objects created from now on
-- ---------------------------------------------------------------------

alter default privileges for role postgres in schema public revoke all on tables from anon, authenticated;
alter default privileges for role postgres in schema public revoke all on sequences from anon, authenticated;
alter default privileges for role postgres in schema public revoke all on functions from anon, authenticated;
-- PUBLIC EXECUTE is a global default; it can only be removed globally.
alter default privileges for role postgres revoke execute on functions from public;

-- ---------------------------------------------------------------------
-- 2. Views
-- ---------------------------------------------------------------------

-- Site Admin Club Management. The view was security invoker over
-- club_directory, which anonymous callers and every signed-in user can read,
-- so it returned every directory row, including notes and official email, to
-- anyone. Rows are now returned only to Site Admins. (Legacy site-admin gate,
-- replaced by the explicit site.clubs.view capability in Slice 7.)
create or replace view public.admin_club_overview
with (security_invoker = true)
as
SELECT cd.id AS directory_id,
    cd.name,
    cd.rugby_code,
    cd.country,
    cd.nation,
    cd.region,
    cd.county,
    cd.town,
    cd.postcode,
    cd.home_ground,
    cd.address,
    cd.website AS directory_website,
    cd.official_email,
    cd.source,
    cd.external_id,
    cd.source_url,
    cd.source_updated_at,
    cd.active AS directory_active,
    cd.verification_status,
    cd.notes,
    cd.constituent_body,
    cd.normalized_key,
    cd.updated_at AS directory_updated_at,
    cd.created_at AS directory_created_at,
    c.id AS club_id,
    c.slug,
    c.status AS club_status,
    c.bio,
    c.website AS club_website,
    c.facebook_url,
    c.address_display,
    c.logo_storage_path,
    c.legacy_logo_path,
    c.created_at AS activated_at,
    c.updated_at AS club_updated_at,
    (c.id IS NOT NULL) AS is_activated,
    COALESCE(admin_counts.club_admin_count, (0)::bigint) AS club_admin_count,
    ((cd.postcode IS NULL) OR (cd.postcode = ''::text)) AS flag_missing_postcode,
    ((cd.town IS NULL) OR (cd.town = ''::text)) AS flag_missing_town,
    ((cd.rugby_code IS NULL) OR (cd.rugby_code = ''::text)) AS flag_missing_rugby_code,
    (dup_key.key_count > 1) AS flag_duplicate_normalized_key,
    ((cd.external_id IS NOT NULL) AND (dup_ext.ext_count > 1)) AS flag_duplicate_external_id,
    (cd.verification_status !~~* '%verified%'::text) AS flag_unverified,
    (cd.active = false) AS flag_inactive,
    ((COALESCE(cd.website, c.website) IS NULL) OR (COALESCE(cd.website, c.website) = ''::text)) AS flag_missing_website,
    ((c.logo_storage_path IS NULL) AND (c.legacy_logo_path IS NULL) AND (cd.logo_storage_path IS NULL)) AS flag_missing_logo,
    ((c.id IS NOT NULL) AND ((c.bio IS NULL) OR (c.bio = ''::text))) AS flag_no_public_profile,
    pending_claim.has_pending AS flag_pending_claim,
    cd.logo_storage_path AS directory_logo_storage_path
   FROM (((((club_directory cd
     LEFT JOIN clubs c ON ((c.directory_id = cd.id)))
     LEFT JOIN LATERAL ( SELECT count(*) AS club_admin_count
           FROM club_memberships cm
          WHERE ((cm.club_id = c.id) AND (cm.role = 'CLUB_ADMIN'::text) AND (cm.status = 'active'::text))) admin_counts ON (true))
     LEFT JOIN LATERAL ( SELECT count(*) AS key_count
           FROM club_directory cd2
          WHERE (cd2.normalized_key = cd.normalized_key)) dup_key ON (true))
     LEFT JOIN LATERAL ( SELECT count(*) AS ext_count
           FROM club_directory cd3
          WHERE ((cd3.source = cd.source) AND (cd3.external_id = cd.external_id))) dup_ext ON (true))
     LEFT JOIN LATERAL ( SELECT (EXISTS ( SELECT 1
                   FROM club_claims cc
                  WHERE ((cc.directory_id = cd.id) AND (cc.status = 'pending'::text)))) AS has_pending) pending_claim ON (true))
  WHERE internal.is_site_admin();

